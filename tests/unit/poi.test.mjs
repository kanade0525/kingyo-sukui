// 紙の持ち。
//
// 「一度に 14 匹すくえる」という指摘が出どころ。
// 乗る量に上限が無く、重さで破れるのも「沈んでいる間だけ」だったので、
// 持ち上げたあとは何匹乗せても絶対に破れなかった。

import { Poi } from '../../assets/js/poi.js?v=202610071522';
import { POI, FISH_KINDS } from '../../assets/js/world.js?v=202610071522';
import { ok, between } from '../lib/assert.mjs';

const ripple = { drop() {} };

/**
 * 紙を実際に動かして、破れるまでの秒数を返す。
 *
 * 式を写して確かめると、式を直したときに試験のほうも一緒に直って
 * しまって何も見ていないことになる。本物の update を回す
 */
function 持ちこたえる(load, { 沈める = false, wet = 1, limit = 12 } = {}) {
  const p = new Poi();
  p.wet = wet;
  p.locked = true;            // 高さを固定して、重さの効きだけを見る
  p.y = 沈める ? -0.06 : POI.restY;
  const y = p.y;
  for (let t = 0; t < limit; t += 1 / 60) {
    p.wet = wet;              // 水から出すと乾いていくので、条件を保つ
    p.update(1 / 60, ripple, load);
    p.y = y; p.vy = 0;        // 高さは動かさない。重さの効きだけを見る
    if (p.broke) return t;
  }
  return Infinity;
}

const 小赤 = FISH_KINDS[0].weight;

export default {
  '紙に乗る量に上限がある': () => {
    // 3cm の小赤の footprint は len^2 * 0.32。
    // 紙の真ん中の平らな所に乗りきる数で頭打ちになる
    const 小赤の面積 = 0.030 * 0.030 * 0.32;
    const 出目金の面積 = 0.045 * 0.045 * 0.32;
    between(Math.floor(POI.hold / 小赤の面積), 2, 4, '小赤が紙に乗る数');
    between(Math.floor(POI.hold / 出目金の面積), 1, 2, '出目金が紙に乗る数');
  },

  '水から出すと、重さで紙が破れる': () => {
    // 沈んでいる間だけ重さを見ていたので、持ち上げたあとは
    // 何匹乗せても破れなかった。水から出た瞬間に全部の重さが乗る
    const 一匹 = 持ちこたえる(小赤);
    const 二匹 = 持ちこたえる(小赤 * 2);
    const 三匹 = 持ちこたえる(小赤 * 3);
    ok(一匹 > 二匹 && 二匹 > 三匹, '匹数が増えても持ちが変わらない');
    // 器へ移すまでに一拍（1.1 秒）見せるので、1 匹はそこを越えられる
    ok(一匹 > 1.8, `1 匹で ${一匹.toFixed(1)} 秒しかもたない`);
    // 3 匹は、見せている間に破れるくらい危うくなければ意味がない
    ok(三匹 < 1.8, `3 匹でも ${三匹.toFixed(1)} 秒もつ`);
  },

  '濡れていない紙のほうが重さに強い': () => {
    ok(持ちこたえる(小赤 * 2, { wet: 0 }) > 持ちこたえる(小赤 * 2, { wet: 1 }),
       '乾いた紙と濡れた紙で持ちが変わらない');
  },

  '沈めているだけでは、重さで破れない': () => {
    // 水の中の金魚は浮力でほとんど重さが無い。
    // 沈めたまま置いておくだけで破れるようでは、掬う前に終わる
    ok(持ちこたえる(小赤 * 2, { 沈める: true, limit: 8 }) === Infinity,
       '沈めたまま置いておくだけで紙が破れる');
    // 水から出したときのほうが、はっきり速く傷む
    ok(持ちこたえる(小赤 * 2) < 持ちこたえる(小赤 * 2, { 沈める: true, limit: 30 }),
       '水から出しても重さの効きが変わらない');
  },
};
