/** これより遠ければ、名前を出さない（km）。離島や国外のため */
const LIMIT = 220;

export function nearestCity(lat, lon) {
  const cosLat = Math.cos((lat * Math.PI) / 180);
  let best = null, bestD = Infinity;
  for (const [ja, en, la, lo] of CITIES) {
    // 平面近似。数百 km の範囲なら、順位を間違えるほどの差は出ない
    const dy = (la - lat) * 111.0;
    const dx = (lo - lon) * 111.0 * cosLat;
    const d = dx * dx + dy * dy;
    if (d < bestD) { bestD = d; best = LANG === 'ja' ? ja : en; }
  }
  return Math.sqrt(bestD) <= LIMIT ? best : null;
}
