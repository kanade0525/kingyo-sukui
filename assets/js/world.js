/**
 * 水槽。縁日の金魚すくいで使うのは「トロ舟（プラ舟）」。
 *
 * リス興業 80L の実寸を採っている。
 *   内寸        850 × 548 × 深さ 187 mm
 *   底の外寸    807 × 500
 *   上の外寸    911 × 602
 *   全高        207 mm
 *
 * 大事なのは、これが垂直な箱ではないこと。底 807 から上 911 まで
 * 片側 52mm も開いた台形で、角には大きな R が付いている。
 * 樹脂を型から抜くための勾配と丸みなので、ここを直角に作ると
 * どれだけ質感を作り込んでも板を貼り合わせた箱にしか見えない。
 *
 * 水面を y = 0 に置く。実際の金魚すくいは縁まで張らず、14〜15cm ほど。
 */
export const TANK = {
  // 水面の高さでの内寸の半分
  halfX: 0.419,
  halfZ: 0.2675,
  depth: 0.145,     // 水面から底まで
  rimTop: 0.042,    // 水面から縁の上端まで（内寸深さ 187mm のうちの残り）
  outBottom: -0.165, // 地面に接する高さ（縁から 207mm 下）
  rimW: 0.0305,     // 上の外寸と内寸の差の半分
  wallT: 0.005,     // 樹脂の肉厚
  // 抜き勾配。高さ 1m あたり外へ開く量。上下の内寸の差から出した
  draftX: 0.1417,
  draftZ: 0.1551,
  cornerR: 0.065,   // 平面で見たときの角の丸み（水面の高さで）
  fillet: 0.026,    // 底と壁のつなぎの丸み
};

/** ある高さでの内寸の半分。壁が傾いているので、高さごとに変わる。 */
export function tankHalfAt(y) {
  return [TANK.halfX + TANK.draftX * y, TANK.halfZ + TANK.draftZ * y];
}


